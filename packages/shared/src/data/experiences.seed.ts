/**
 * Filter helper ensuring Rule 4 & moderation safety:
 * Only returns records with moderation_status === 'published' AND publication_consent === true
 */
export function getPublishedExperiencesForProduct(productSlugOrId: string): CustomerExperienceRecord[] {
  return DEMO_EXPERIENCES_SEED.filter(
    (exp) =>
      (exp.product_slug === productSlugOrId || exp.product_id === productSlugOrId) &&
      exp.moderation_status === "published" &&
      exp.publication_consent === true
  );
}
